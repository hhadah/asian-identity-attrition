#!/usr/bin/env Rscript
#
# Between-model comparisons from the preserved 1,000-replication bootstrap
# Date: November 5th, 2026
# Builds Tables A.3/A.4 and their prose fragments from validated saved results.
# Never estimates a model, reruns a bootstrap, or modifies raw checkpoints.
# Run after script 45 when bootstrap outputs change. Listed, but not enabled,
# in programs/95-make-all.R like the other final-round table generators.
# ASIAN_BOOTSTRAP_OUTPUT_DIR optionally redirects all outputs for inspection.
# Results -> output/tables/tab-between-model-second-gen.tex
#         -> output/tables/tab-between-model-third-gen.tex
#         -> output/tables/bootstrap-comparison-values.csv
#         -> output/tables/bootstrap-comparison-provenance.json
#         -> output/tables/fragments/bootstrap-*.tex

resolve_root <- function() {
  env_root <- Sys.getenv("ASIAN_IDENTITY_ROOT")
  if (nzchar(env_root)) return(normalizePath(env_root, mustWork = TRUE))
  if (exists("git_mdir", inherits = TRUE)) {
    return(normalizePath(get("git_mdir", inherits = TRUE), mustWork = TRUE))
  }
  args <- commandArgs(trailingOnly = TRUE)
  normalizePath(if (length(args) >= 1L) args[[1L]] else getwd(), mustWork = TRUE)
}
root <- resolve_root()
if (!requireNamespace("jsonlite", quietly = TRUE)) {
  stop("Package jsonlite is required for the provenance manifest.", call. = FALSE)
}
source(file.path(root, "programs", "bootstrap-comparison-data.R"), local = TRUE)
checked <- read_bootstrap_comparisons(file.path(root, "data", "raw", "bootstrapping-data"))
dat <- checked$data
out_dir <- Sys.getenv("ASIAN_BOOTSTRAP_OUTPUT_DIR",
                      unset = file.path(root, "output", "tables"))
dir.create(out_dir, recursive = TRUE, showWarnings = FALSE)
fragment_dir <- file.path(out_dir, "fragments")
dir.create(fragment_dir, recursive = TRUE, showWarnings = FALSE)
run_id <- format(Sys.time(), "%Y%m%d-%H%M%S")

variables <- c(value = "Anti-Asian Bias", Female = "Female",
               MomGradCollege = "College Graduate: Mother",
               DadGradCollege = "College Graduate: Father")
outcomes <- c("Asian_only", "White_only", "Asian_and_White")
column_head <- c(
  r"(\toprule)",
  r"( & \multicolumn{1}{c}{Asian Only} & \multicolumn{1}{c}{White Only} & \multicolumn{1}{c}{Asian \& White} \\)",
  r"(\cmidrule(l{3pt}r{3pt}){2-2} \cmidrule(l{3pt}r{3pt}){3-3} \cmidrule(l{3pt}r{3pt}){4-4})",
  r"(\midrule)")
stars_note <- r"(\multicolumn{4}{l}{\rule{0pt}{1em}* p $<$ 0.1, ** p $<$ 0.05, *** p $<$ 0.01}\\)"
notes <- c(
  r"(\item[1] \footnotesize{Cells subtract the second model's median AME from the first model's, using equation (\ref{eq:multinomial_logit}). Bias AMEs are per index unit; binary AMEs are 0-to-1 probability differences.})",
  r"(\item[2] \footnotesize{Parentheses report approximate standard errors: each model's 95\% bootstrap percentile-interval width divided by $2\times1.96$, then combined in quadrature across the two models assuming independent samples. Stars use two-sided normal $z$-tests.})",
  r"(\item[3] \footnotesize{Models use 1{,}000 individual bootstrap resamples within region $\times$ year, region $\times$ year fixed effects, quartic age, local Asian population share, and CPS person weights. Inference does not account for within-state dependence.})")
second_notes <- notes
second_notes[[1L]] <- r"(\item[1] \footnotesize{Cells report median AMEs for Asian father--White mother (AW) families minus those for White father--Asian mother (WA) families, using equation (\ref{eq:multinomial_logit}). Bias AMEs are per index unit; binary AMEs are 0-to-1 probability differences.})"

panel <- function(model_a, model_b, title) {
  rows <- dat[dat$model_a == model_a & dat$model_b == model_b, ]
  lines <- paste0(sprintf(r"(\multicolumn{4}{l}{\textit{%s}} )", title), r"(\\*)")
  for (variable in names(variables)) {
    x <- rows[rows$variable == variable, ]
    x <- x[match(outcomes, x$outcome), ]
    estimates <- sprintf("$%.3f$%s", x$diff_est, x$sig)
    errors <- sprintf("($%.3f$)", x$se_diff)
    lines <- c(lines, r"(\addlinespace)",
               paste0(variables[[variable]], " & ",
                      paste(estimates, collapse = " & "), r"(\\*)"),
               paste0(" & ", paste(errors, collapse = " & "), r"(\\)"))
  }
  lines
}

second <- c(
  "% Generated by programs/54-make-bootstrap-comparison-tables.R; do not edit.",
  r"(\begin{table}[H])", r"(\centering)",
  r"(\caption{Between-Model Tests of Average Marginal Effects: Second-Generation AW vs.\ WA \label{tab:between-model-second}})",
  r"(\fontsize{10}{12}\selectfont)", r"(\begin{threeparttable})",
  r"(\begin{tabular}[t]{lccc})", column_head,
  panel("Second gen: AW", "Second gen: WA", "Panel A: AW vs.\\ WA"),
  r"(\bottomrule)", stars_note, r"(\end{tabular})",
  r"(\begin{tablenotes})", r"(\small)", second_notes,
  r"(\end{tablenotes})", r"(\end{threeparttable})", r"(\end{table})")
third <- c(
  "% Generated by programs/54-make-bootstrap-comparison-tables.R; do not edit.",
  r"(\begingroup)", r"(\fontsize{10}{12}\selectfont)",
  r"(\begin{ThreePartTable})", r"(\begin{TableNotes})", r"(\small)", notes,
  r"(\item[4] \footnotesize{GP denotes Asian-born grandparents. Third-generation individuals are native-born with at least one Asian-born grandparent.})",
  r"(\end{TableNotes})", r"(\begin{longtable}{lccc})",
  r"(\caption{Between-Model Tests of Average Marginal Effects: Third-Generation by Asian Grandparent Count \label{tab:between-model-third}}\\)",
  column_head, r"(\endfirsthead)",
  r"(\multicolumn{4}{c}{\tablename\ \thetable{} -- \textit{continued from previous page}}\\)",
  column_head, r"(\endhead)", r"(\midrule)",
  r"(\multicolumn{4}{r}{\textit{Continued on next page}}\\)",
  r"(\endfoot)", r"(\bottomrule)", stars_note,
  r"(\insertTableNotes)", r"(\endlastfoot)",
  panel("Third gen: 1 Asian GP", "Third gen: 2 Asian GP",
        "Panel A: One Asian GP vs.\\ Two Asian GP"), r"(\midrule)",
  panel("Third gen: 1 Asian GP", "Third gen: 3 Asian GP",
        "Panel B: One Asian GP vs.\\ Three Asian GP"), r"(\midrule)",
  panel("Third gen: 2 Asian GP", "Third gen: 3 Asian GP",
        "Panel C: Two Asian GP vs.\\ Three Asian GP"),
  r"(\end{longtable})", r"(\end{ThreePartTable})", r"(\endgroup)")
writeLines(second, file.path(out_dir, "tab-between-model-second-gen.tex"), useBytes = TRUE)
writeLines(third, file.path(out_dir, "tab-between-model-third-gen.tex"), useBytes = TRUE)

# Only the scalar comparisons cited in prose; percentages are probability
# differences multiplied by 100, not relative percentage changes.
fragment_rows <- list(
  "bootstrap-aw-wa-bias-white" = c("value", "White_only", "Second gen: AW", "Second gen: WA"),
  "bootstrap-aw-wa-female-mixed" = c("Female", "Asian_and_White", "Second gen: AW", "Second gen: WA"),
  "bootstrap-gp13-female-white" = c("Female", "White_only", "Third gen: 1 Asian GP", "Third gen: 3 Asian GP"),
  "bootstrap-gp13-female-mixed" = c("Female", "Asian_and_White", "Third gen: 1 Asian GP", "Third gen: 3 Asian GP"))
fragments <- list()
for (prefix in names(fragment_rows)) {
  key <- fragment_rows[[prefix]]
  x <- dat[dat$variable == key[[1L]] & dat$outcome == key[[2L]] &
             dat$model_a == key[[3L]] & dat$model_b == key[[4L]], ]
  if (nrow(x) != 1L) stop(sprintf("Ambiguous prose fragment: %s", prefix), call. = FALSE)
  values <- c("diff-pp" = sprintf("%.1f", 100 * x$diff_est),
              "se-pp" = sprintf("%.1f", 100 * x$se_diff),
              "p" = sprintf("%.3f", x$p_value))
  for (stat in names(values)) {
    name <- sprintf("%s-%s.tex", prefix, stat)
    writeLines(sprintf("%s%%", values[[stat]]), file.path(fragment_dir, name),
               useBytes = TRUE)
    fragments[[name]] <- values[[stat]]
  }
}

manifest_values <- dat
manifest_values$replications <- checked$provenance$replications
manifest_values$run_id <- run_id
write.csv(manifest_values, file.path(out_dir, "bootstrap-comparison-values.csv"),
          row.names = FALSE)
provenance <- checked$provenance
provenance$run_id <- run_id
provenance$source_directory <- "data/raw/bootstrapping-data"
provenance$generator <- "programs/54-make-bootstrap-comparison-tables.R"
provenance$generator_sha256 <- digest::digest(
  file = file.path(root, provenance$generator), algo = "sha256")
provenance$reader_sha256 <- digest::digest(
  file = file.path(root, "programs", "bootstrap-comparison-data.R"), algo = "sha256")
provenance$R_version <- R.version.string
provenance$prose_fragments <- fragments
jsonlite::write_json(provenance,
                     file.path(out_dir, "bootstrap-comparison-provenance.json"),
                     pretty = TRUE, auto_unbox = TRUE, digits = NA)
cat(sprintf("PASS: %d comparison rows from %d-replication checkpoints; two tables and %d prose fragments; no fits or bootstrap runs.\n",
            nrow(dat), provenance$replications, length(fragments)))
